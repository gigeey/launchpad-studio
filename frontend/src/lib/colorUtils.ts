/**
 * Adjust a hex color for dark/light mode bubble display.
 *
 * Light mode: slightly darken for good contrast on white backgrounds.
 * Dark mode:  reduce lightness & saturation so it feels muted/soft against dark backgrounds.
 */

function hexToHSL(hex: string): { h: number; s: number; l: number } {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  if (!result) return { h: 0, s: 0, l: 50 };

  const r = parseInt(result[1], 16) / 255;
  const g = parseInt(result[2], 16) / 255;
  const b = parseInt(result[3], 16) / 255;

  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;

  if (max === min) return { h: 0, s: 0, l: l * 100 };

  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);

  let h: number;
  switch (max) {
    case r: h = ((g - b) / d + (g < b ? 6 : 0)) / 6; break;
    case g: h = ((b - r) / d + 2) / 6; break;
    default: h = ((r - g) / d + 4) / 6; break;
  }

  return { h: h * 360, s: s * 100, l: l * 100 };
}

function hslToHex(h: number, s: number, l: number): string {
  s /= 100;
  l /= 100;

  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;

  let r: number, g: number, b: number;
  if (h < 60) { r = c; g = x; b = 0; }
  else if (h < 120) { r = x; g = c; b = 0; }
  else if (h < 180) { r = 0; g = c; b = x; }
  else if (h < 240) { r = 0; g = x; b = c; }
  else if (h < 300) { r = x; g = 0; b = c; }
  else { r = c; g = 0; b = x; }

  const toHex = (v: number) => Math.round((v + m) * 255).toString(16).padStart(2, "0");
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

/**
 * Returns the bubble color adjusted for the current theme.
 *
 * Light mode: return the original color as-is.
 * Dark mode:  pull lightness down and desaturate so it's muted on dark backgrounds.
 *
 * Reference: original blue #007AFF (l≈50%) → dark mode #264F78 (l≈30%).
 */
export function adjustBubbleColor(hex: string, isDark: boolean): string {
  if (!isDark) return hex;

  const { h, s, l } = hexToHSL(hex);
  const darkL = Math.min(l, 30);
  const darkS = Math.min(s, s * 0.60);
  return hslToHex(h, darkS, darkL);
}
